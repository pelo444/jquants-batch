--------------------------------------------------------------------------------
-- 日々の確認(/daily): 「確認した」を押したときの画面の内容を残す
-- 実行ユーザー: GD_JQUANTS(列を足すだけ。CLAUDE_RO の GRANT・シノニムは ddl/32 のままでよい)
--
-- 【何のための列か】
--   「確認した」を押した時点で画面に出ていた内容(期間・データの最新日・出来事・値動き・
--   これからの予定)を JSON のまま残し、あとから「過去の確認」のプルダウンで同じ見た目で開く。
--   日付を選んで表示していたときは、その内容を残す。
--   この列を足す前に押した行は PAYLOAD が空(画面では「内容なし」)。
--
-- 【大きさ】1回あたり数十KB。朝夕に押しても1年で数十MB。
--
-- 前提: ddl/32_daily_seen.sql を実行済み。
--------------------------------------------------------------------------------
ALTER TABLE jnl_daily_seen ADD (
    payload CLOB,
    CONSTRAINT jnl_daily_seen_payload_json CHECK (payload IS JSON)
);

COMMENT ON COLUMN jnl_daily_seen.payload IS '「確認した」を押したときに画面に出ていた内容(JSON)。過去の確認として同じ見た目で開く';
